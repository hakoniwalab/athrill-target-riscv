# What each generated file takes from riscv-opcodes and what comes from this
# generator (MIT, this repository).
ENCODING_CONTENTS = """\
MASK_/MATCH_ constants copied from riscv-opcodes' encoding.out.h."""
TABLE_CONTENTS = """\
Masks and matches come from riscv-opcodes. The selection of enabled
instructions (ENABLED), the operand and immediate layout per entry and the
executor names come from the generator."""
COMPRESSED_CONTENTS = """\
Masks, matches and immediate bit layouts come from riscv-opcodes. The
expansion of each compressed instruction into its base instruction (base
mnemonic, implied registers, immediate kind) is the generator's
hand-written COMPRESSED_EXPANSIONS table; riscv-opcodes does not describe
it."""


# riscv-opcodes marks registers that must be nonzero (rd_n0, ...) without
# saying what the zero encoding is. For these instructions rd = x0 is a HINT
# (RISC-V unprivileged specification, RVC HINT table): it executes and has
# no effect, so it must not raise an illegal instruction. For the others
# (c.lwsp, c.ldsp, c.addiw, ...) rd = x0 is reserved.
RD_ZERO_IS_HINT = {"c_li", "c_lui", "c_mv", "c_add", "c_slli"}


def notice(license_text, contents, spdx):
    def comment(text):
        return "".join(" * " + line + "\n" if line else " *\n"
                       for line in text.splitlines())
    return (f"/* SPDX-License-Identifier: {spdx}\n *\n"
            " * Generated by tools/generate_riscv_opcodes.py (MIT) from\n"
            f" * riscv-opcodes commit {COMMIT}.\n"
            " * Do not edit; regenerate with\n"
            " *   tools/generate_riscv_opcodes.py /path/to/riscv-opcodes\n"
            " *\n" + comment(contents) +
            " *\n * riscv-opcodes license (for the data taken from it):\n" +
            comment(license_text) + " */\n")


def operands(fields):
    flags = []
    for field, flag in (("rd", "RISCV_OPERAND_RD"),
                        ("rs1", "RISCV_OPERAND_RS1"),
                        ("rs2", "RISCV_OPERAND_RS2"),
                        ("csr", "RISCV_OPERAND_CSR"),
                        ("zimm", "RISCV_OPERAND_ZIMM")):
        if field in fields:
            flags.append(flag)
    if any(field in fields for field in ("fm", "pred", "succ")):
        flags.append("RISCV_OPERAND_FENCE")
    return " | ".join(flags) if flags else "0U"


def immediate(fields):
    if any(field in fields for field in ("imm12", "shamtd", "shamtw")):
        return "RISCV_IMMEDIATE_I"
    if "imm12hi" in fields:
        return "RISCV_IMMEDIATE_S"
    if "bimm12hi" in fields:
        return "RISCV_IMMEDIATE_B"
    if "imm20" in fields:
        return "RISCV_IMMEDIATE_U"
    if "jimm20" in fields:
        return "RISCV_IMMEDIATE_J"
    return "RISCV_IMMEDIATE_NONE"


def write_table(path, instructions, header):
    lines = [header, '#include "riscv_decode.h"\n\n',
             "const RiscvDispatchEntry riscv_instruction_table[] = {\n"]
    entries = []
    for mnemonic in ENABLED:
        data = instructions[mnemonic]
        function = mnemonic.replace(".", "_")
        display_name = mnemonic.replace("_", ".")
        fields = data["variable_fields"]
        entries.append(
            "\t{\n"
            f"\t\t{data['mask']}U, {data['match']}U,\n"
            f"\t\t{operands(fields)}, {immediate(fields)},\n"
            f"\t\top_exec_{function}, \"{display_name}\", "
            f"\"{data['extension'][0]}\"\n\t}}")
    lines.append(",\n".join(entries))
    lines += ["\n};\n\n", "const uint32 riscv_instruction_table_count =\n",
              "\t(uint32)(sizeof(riscv_instruction_table) /\n",
              "\t\tsizeof(riscv_instruction_table[0]));\n"]
    path.write_text("".join(lines))


def load_upstream_fields(root):
    """Return compressed source ranges and documented immediate bit layouts."""
    with (root / "arg_lut.csv").open(newline="") as stream:
        ranges = {row[0]: (int(row[2]), int(row[1]))
                  for row in csv.reader(stream)}
    tree = ast.parse((root / "src/riscv_opcodes/constants.py").read_text())
    latex = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
                isinstance(target, ast.Name) and target.id == "latex_mapping"
                for target in node.targets):
            latex = ast.literal_eval(node.value)
            break
    return ranges, latex


def immediate_slices(fields, ranges, latex):
    slices = []
    width = 0
    nonzero = False
    signed = False
    for field in fields:
        if field not in latex or "imm[" not in latex[field]:
            continue
        source_lo, source_hi = ranges[field]
        prefix, bits = latex[field].split("[", 1)
        bits = bits.split("]", 1)[0]
        signed |= "uimm" not in prefix
        parts = bits.replace("$\\vert$", "|").split("|")
        source = source_hi
        for part in parts:
            bounds = [int(value) for value in part.split(":")]
            dest_hi = bounds[0]
            dest_lo = bounds[-1]
            count = dest_hi - dest_lo + 1
            slices.append((source - count + 1, dest_lo, count))
            source -= count
            width = max(width, dest_hi + 1)
        nonzero |= "nz" in latex[field].split("[", 1)[0]
    return slices, width if signed else 0, nonzero


def register_recipe(value, ranges):
    if value is None:
        return ("RISCV_COMPRESSED_REGISTER_NONE", 0, 0)
    if isinstance(value, int):
        return ("RISCV_COMPRESSED_REGISTER_FIXED", value, 0)
    lo, hi = ranges[value]
    kind = ("RISCV_COMPRESSED_REGISTER_PRIME" if value.endswith("_p") else
            "RISCV_COMPRESSED_REGISTER_FIELD")
    return (kind, lo, hi - lo + 1)


def write_compressed(path, instructions, header, ranges, latex):
    """Write RV64C expansion rows entirely from upstream encoding metadata."""
    missing = sorted(name for name in COMPRESSED_EXPANSIONS
                     if name not in instructions)
    if missing:
        raise SystemExit("missing compressed definitions: " + ", ".join(missing))
    entries = []
    for name, semantic in COMPRESSED_EXPANSIONS.items():
        data = instructions[name]
        base, rd, rs1, rs2, kind = semantic
        slices, width, nonzero = immediate_slices(
            data["variable_fields"], ranges, latex)
        # RV64 shift amount zero is legal.  c.nop's zero immediate is its
        # canonical encoding, despite the shared upstream nz field name.
        if name in ("c_nop", "c_addi", "c_srli", "c_srai", "c_slli"):
            nonzero = False
        regs = [register_recipe(value, ranges) for value in (rd, rs1, rs2)]
        scale = min((destination for _, destination, _ in slices), default=0)
        invalid = ["RISCV_COMPRESSED_INVALID_IMMEDIATE"] if nonzero else []
        if (isinstance(rd, str) and rd.endswith("n0") and name != "c_addi"
                and name not in RD_ZERO_IS_HINT):
            invalid.append("RISCV_COMPRESSED_INVALID_RD_ZERO")
        if rd == "rd_n2":
            if name not in RD_ZERO_IS_HINT:
                invalid.append("RISCV_COMPRESSED_INVALID_RD_ZERO")
            invalid.append("RISCV_COMPRESSED_INVALID_RD_X2")
        # c.slli and c.add read rs1 from the rd field: the same HINT rule.
        if (isinstance(rs1, str) and rs1.endswith("n0") and name != "c_addi"
                and name not in RD_ZERO_IS_HINT):
            invalid.append("RISCV_COMPRESSED_INVALID_RS1_ZERO")
        if isinstance(rs2, str) and rs2.endswith("n0"):
            invalid.append("RISCV_COMPRESSED_INVALID_RS2_ZERO")
        invalid_value = " | ".join(invalid) if invalid else "0U"
        lines = ["\t{", f"\t\t{data['mask']}U, {data['match']}U, "
                 f"{instructions[base]['match']}U,",
                 f"\t\t{{{{{regs[0][0]}, {regs[0][1]}U, {regs[0][2]}U}},",
                 f"\t\t {{{regs[1][0]}, {regs[1][1]}U, {regs[1][2]}U}},",
                 f"\t\t {{{regs[2][0]}, {regs[2][1]}U, {regs[2][2]}U}}}},",
                 f"\t\tRISCV_IMMEDIATE_{kind}, {width}U, {scale}U, "
                 f"{invalid_value}, "
                 f"{len(slices)}U,",
                 "\t\t{" + ", ".join(
                     f"{{{src}U, {dst}U, {count}U}}"
                     for src, dst, count in slices) + "}", "\t}"]
        key = ((int(data["match"], 16) >> 13) << 2) | \
              (int(data["match"], 16) & 3)
        entries.append((key, int(data["mask"], 16).bit_count(),
                        "\n".join(lines)))
    entries.sort(key=lambda item: (item[0], -item[1]))
    ranges_by_key = []
    for key in range(32):
        indices = [index for index, entry in enumerate(entries)
                   if entry[0] == key]
        start = indices[0] if indices else 0
        ranges_by_key.append((start, len(indices)))
    body = [header, '#include "riscv_decode.h"\n\n',
            "const RiscvCompressedEntry riscv_compressed_table[] = {\n",
            ",\n".join(entry for _, _, entry in entries), "\n};\n\n",
            "const uint32 riscv_compressed_table_count =\n",
            "\t(uint32)(sizeof(riscv_compressed_table) /\n",
            "\t\tsizeof(riscv_compressed_table[0]));\n\n",
            "const uint8 riscv_compressed_ranges[32][2] = {\n\t",
            ",\n\t".join(f"{{{start}U, {count}U}}"
                           for start, count in ranges_by_key),
            "\n};\n"]
    path.write_text("".join(body))


def main():
    root = pathlib.Path(sys.argv[1]).resolve()
    actual = subprocess.check_output(
        ["git", "-C", str(root), "rev-parse", "HEAD"], text=True).strip()
    if actual != COMMIT:
        raise SystemExit(f"expected riscv-opcodes {COMMIT}, got {actual}")
    subprocess.run(
        [sys.executable, "-c", "from riscv_opcodes.parse import main; main()",
         "-c", *EXTENSIONS], cwd=root,
        env={**os.environ, "PYTHONPATH": str(root / "src")}, check=True)
    destination = pathlib.Path(__file__).resolve().parents[1] / "src/cpu/cpu_dec"
    license_text = (root / "LICENSE").read_text().rstrip()
    header = notice(license_text, ENCODING_CONTENTS, "BSD-3-Clause")
    definitions = []
    for line in (root / "encoding.out.h").read_text().splitlines():
        if re.match(r"#define (MATCH|MASK)_[A-Z0-9_]+\s", line):
            definitions.append(line.replace("_RISCV_UL(", "(").replace(
                "_RISCV_ULL(", "("))
    (destination / "riscv_encoding.h").write_text(
        header + "#ifndef RISCV_ENCODING_H\n#define RISCV_ENCODING_H\n\n" +
        "\n".join(definitions) + "\n\n#endif\n")
    instructions = json.loads((root / "instr_dict.json").read_text())
    write_table(destination / "riscv_instruction_table.c", instructions,
                notice(license_text, TABLE_CONTENTS, "BSD-3-Clause AND MIT"))
    ranges, latex = load_upstream_fields(root)
    write_compressed(destination / "riscv_compressed_table.c", instructions,
                     notice(license_text, COMPRESSED_CONTENTS, "BSD-3-Clause AND MIT"),
                     ranges, latex)


if __name__ == "__main__":
    main()
